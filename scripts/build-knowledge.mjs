// Reads the newsletter markdown files and emits lib/knowledge.ts as a single
// committed-at-build-time module. Keeping the knowledge base inlined means the
// serverless chat function never touches the filesystem at runtime, and the
// answers stay grounded in exactly these eight files.
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const sourceDir = join(root, "newsletters");
const outFile = join(root, "lib", "knowledge.ts");

const files = readdirSync(sourceDir)
  .filter((f) => f.endsWith(".md"))
  .sort();

if (files.length === 0) {
  throw new Error(`No newsletters found in ${sourceDir}`);
}

// Pull a human-readable title from the first markdown heading, falling back to
// the filename.
function titleOf(md, filename) {
  const m = md.match(/^#\s+(.+)$/m);
  return m ? m[1].trim() : filename.replace(/\.md$/, "");
}

const sections = files.map((filename) => {
  const md = readFileSync(join(sourceDir, filename), "utf8");
  return {
    filename,
    title: titleOf(md, filename),
    content: md.trim(),
  };
});

const banner = `// AUTO-GENERATED by scripts/build-knowledge.mjs — do not edit by hand.
// Source: newsletters/*.md (${sections.length} files)\n`;

const body =
  banner +
  `\nexport interface Newsletter {\n  filename: string;\n  title: string;\n  content: string;\n}\n\n` +
  `export const NEWSLETTERS: Newsletter[] = ${JSON.stringify(sections, null, 2)};\n\n` +
  `// The full corpus, formatted for inclusion in the system prompt.\n` +
  `export const KNOWLEDGE_BASE: string = NEWSLETTERS.map(\n` +
  `  (n) => \`<newsletter title="\${n.title}" file="\${n.filename}">\\n\${n.content}\\n</newsletter>\`\n` +
  `).join("\\n\\n");\n`;

mkdirSync(join(root, "lib"), { recursive: true });
writeFileSync(outFile, body, "utf8");

console.log(
  `Wrote ${outFile} with ${sections.length} newsletters (${KNOWLEDGE_SIZE(sections)} chars of content).`
);

function KNOWLEDGE_SIZE(s) {
  return s.reduce((acc, n) => acc + n.content.length, 0).toLocaleString();
}
